//! Compiles every `recipes/*.hcs` into the agent's recipe list, so adding or accepting a recipe never means editing a list by hand
//! (two agents adding recipes at once used to collide on it). The list is in `$OUT_DIR/recipes_list.rs`, included by `mcp.rs`.

use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap_or_else(|_| ".".into()));
    let dir = manifest.join("../../recipes");
    println!("cargo:rerun-if-changed={}", dir.display());
    println!("cargo:rerun-if-changed=build.rs");
    let mut files: Vec<PathBuf> = std::fs::read_dir(&dir).map(|d| d.filter_map(|e| e.ok()).map(|e| e.path()).filter(|p| p.extension().is_some_and(|x| x == "hcs")).collect()).unwrap_or_default();
    files.sort();
    let mut src = String::from("/// Built-in example recipes (compiled into the binary so agents can read them anywhere; generated by build.rs).\nconst RECIPES: &[(&str, &str)] = &[\n");
    for f in &files {
        let name = f.file_stem().map(|s| s.to_string_lossy().into_owned()).unwrap_or_default();
        let abs = std::fs::canonicalize(f).unwrap_or_else(|_| f.clone());
        // `\?\C:\...` (a canonical Windows path) is fine for include_str!, and {:?} escapes the backslashes
        src.push_str(&format!("    ({name:?}, include_str!({:?})),\n", abs.to_string_lossy()));
    }
    src.push_str("];\n");
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap_or_else(|_| ".".into())).join("recipes_list.rs");
    if let Err(e) = std::fs::write(&out, src) {
        eprintln!("build.rs: cannot write {}: {e}", out.display());
        std::process::exit(1);
    }
}
