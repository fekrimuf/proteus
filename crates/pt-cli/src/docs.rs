//! The documentation harness: `pt status` writes every number the docs quote from the code and the
//! result files (so no count is typed by hand), and `pt docs-check` fails when the docs go stale,
//! break a link, exceed their size budget or break a rule from CLAUDE.md.

use serde_json::Value;
use std::path::{Path, PathBuf};
use std::process::Command;

use crate::registry::{Command as Cmd, Kind, Param};

const STATE_FILE: &str = "docs/generated/state.md";
/// The command table, generated from the registry (`crate::registry::markdown`).
const COMMANDS_FILE: &str = "docs/generated/commands.md";

pub const STATUS: Cmd = Cmd {
    name: "status",
    tool: "status",
    summary: "Print the measured state: every count and score the docs may quote, from the code and the result files. With --write it stores the state in docs/generated/state.md and the command table in docs/generated/commands.md.",
    heavy: false,
    params: &[Param::flag("write", Kind::Bool, "store the state and the command table under docs/generated/")],
    run: status_cmd,
};

pub const DOCS_CHECK: Cmd = Cmd {
    name: "docs-check",
    tool: "docs_check",
    summary: "Check the documentation: size budgets, broken links, banned headings, mangled Windows paths, the STATUS date, the index, and that the generated state and command table are current. Exit 1 on any problem.",
    heavy: false,
    params: &[],
    run: check_cmd,
};
const STATUS_BUDGET: usize = 8 * 1024;
const DOC_BUDGET: usize = 50 * 1024;
/// Files that only ever grow and are never read at startup.
const APPEND_ONLY: &[&str] = &["docs/LOG.md"];
/// Headings CLAUDE.md forbids ("where we'll lose" style sections), matched case-insensitively.
const BANNED_HEADINGS: &[&str] = &["honest unknown", "honest sizing", "caveat", "limits", "limitations", "what we can't", "what we cannot", "what this does not show", "not built yet", "where we'll lose"];

fn root() -> PathBuf {
    for c in [".", "../.."] {
        let p = PathBuf::from(c);
        if p.join("Cargo.toml").is_file() && p.join("docs").is_dir() {
            return p;
        }
    }
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn read(p: &Path) -> String {
    std::fs::read_to_string(p).unwrap_or_default().replace("\r\n", "\n")
}

fn walk(dir: &Path, ext: &str, out: &mut Vec<PathBuf>) {
    let Ok(rd) = std::fs::read_dir(dir) else { return };
    let mut entries: Vec<PathBuf> = rd.filter_map(|e| e.ok()).map(|e| e.path()).collect();
    entries.sort();
    for p in entries {
        if p.is_dir() {
            walk(&p, ext, out);
        } else if p.extension().is_some_and(|x| x == ext) {
            out.push(p);
        }
    }
}

/// Minimal CSV reader (quotes, doubled quotes, newlines inside quotes).
fn parse_csv(text: &str) -> Vec<Vec<String>> {
    let (mut rows, mut row, mut field, mut quoted) = (vec![], vec![], String::new(), false);
    let mut it = text.chars().peekable();
    while let Some(c) = it.next() {
        match (c, quoted) {
            ('"', true) if it.peek() == Some(&'"') => {
                field.push('"');
                it.next();
            }
            ('"', _) => quoted = !quoted,
            (',', false) => row.push(std::mem::take(&mut field)),
            ('\n', false) => {
                row.push(std::mem::take(&mut field));
                rows.push(std::mem::take(&mut row));
            }
            ('\r', false) => {}
            _ => field.push(c),
        }
    }
    if !field.is_empty() || !row.is_empty() {
        row.push(field);
        rows.push(row);
    }
    rows
}

fn json_of(p: &Path) -> Value {
    serde_json::from_str(&read(p)).unwrap_or(Value::Null)
}

/// Every number and list the docs may quote, derived from the repository itself. Deterministic: it
/// reads only committed files, so CI can regenerate it and compare.
pub fn state_text(root: &Path) -> String {
    let mut s = String::new();
    s.push_str("# Measured state\n\nGenerated by `pt status --write` from the code and the result files. Do not edit by hand; `pt docs-check` fails when it is stale.\n\n");
    s.push_str("| Fact | Value | Source |\n|---|---|---|\n");

    s.push_str(&format!("| Node types | {} | `pt_graph::all_schemas()` |\n", pt_graph::all_schemas().len()));
    s.push_str(&format!("| Registered commands | {} (each also an agent tool) | `crates/pt-cli/src/registry.rs`; table in `docs/generated/commands.md` |\n", crate::registry::ALL.len()));
    s.push_str(&format!("| Agent tools | {} | `tools/list` of `pt mcp` |\n", crate::mcp::tool_count()));

    let mut rs = vec![];
    walk(&root.join("crates"), "rs", &mut rs);
    let tests: usize = rs.iter().map(|p| read(p).lines().filter(|l| l.trim() == "#[test]").count()).sum();
    s.push_str(&format!("| Test functions | {} in {} source files | `#[test]` under `crates/` (run `cargo test --workspace --release` for pass/fail) |\n", tests, rs.len()));

    let mut hcs = vec![];
    walk(&root.join("recipes"), "hcs", &mut hcs);
    let golden = json_of(&root.join("recipes/golden.json"));
    s.push_str(&format!("| Recipes | {} files, {} golden hashes | `recipes/`, `recipes/golden.json` |\n", hcs.len(), golden.as_object().map_or(0, |o| o.len())));

    let gym = json_of(&root.join("gym/baseline.json"));
    if let Some(tasks) = gym["tasks"].as_array() {
        let count = |k: &str| tasks.iter().filter(|t| t["kind"] == k).count();
        let m = |k: &str| gym["mean"][k].as_f64().unwrap_or(0.0);
        s.push_str(&format!("| Gym tasks | {} ({} build, {} repair, {} edit); mean score oracle {:.3}, perturbation agent {:.3}, null agent {:.3} | `gym/baseline.json` |\n", tasks.len(), count("build"), count("repair"), count("edit"), m("oracle"), m("perturbed"), m("null_agent")));
    }

    let ledger = parse_csv(&read(&root.join("corpus/LEDGER.csv")));
    if ledger.len() > 1 {
        let mut classes: std::collections::BTreeMap<String, usize> = Default::default();
        for r in &ledger[1..] {
            *classes.entry(r.get(3).cloned().unwrap_or_default()).or_default() += 1;
        }
        let by = classes.iter().map(|(k, v)| format!("{k} {v}")).collect::<Vec<_>>().join(", ");
        s.push_str(&format!("| Licence ledger | {} rows ({}) | `corpus/LEDGER.csv` |\n", ledger.len() - 1, by));
    }

    let mut scenes = vec![];
    walk(&root.join("scenes"), "hcs", &mut scenes);
    let names: Vec<String> = scenes.iter().filter_map(|p| p.file_stem().map(|n| n.to_string_lossy().to_string())).collect();
    s.push_str(&format!("| Worlds | {} | `scenes/*.hcs` |\n", names.join(", ")));

    s.push_str("\n## Scorecard runs\n\n| Run | Scene | Rows passed | When (UTC) |\n|---|---|---|---|\n");
    let mut cards = vec![];
    walk(&root.join("corpus/results"), "json", &mut cards);
    cards.retain(|p| p.file_name().is_some_and(|n| n == "scorecard.json"));
    let mut rows: Vec<(String, String, String, String)> = cards
        .iter()
        .map(|p| {
            let j = json_of(p);
            let dir = p.parent().and_then(|d| d.strip_prefix(root.join("corpus/results")).ok()).map(|d| d.to_string_lossy().replace('\\', "/")).unwrap_or_default();
            (j["when"].as_str().unwrap_or("").to_string(), dir, j["scene"].as_str().unwrap_or("").to_string(), format!("{} of {}", j["pass"], j["total"]))
        })
        .collect();
    rows.sort();
    for (when, dir, scene, pass) in &rows {
        s.push_str(&format!("| `{dir}` | `{scene}` | {pass} | {when} |\n"));
    }
    s.push_str("\nA run whose engine rows were not measured shows fewer rows passed against a smaller total; its report names them.\n");
    s
}

fn git(args: &[&str]) -> Option<String> {
    let o = Command::new("git").args(args).output().ok()?;
    o.status.success().then(|| String::from_utf8_lossy(&o.stdout).trim().to_string())
}

/// `pt status [--write]`: print the measured state; with `--write` store it in `docs/generated/state.md`.
pub fn status_cmd(args: &[String]) -> Result<(), String> {
    let root = root();
    let text = state_text(&root);
    if args.iter().any(|a| a == "--write") {
        let p = root.join(STATE_FILE);
        if let Some(dir) = p.parent() {
            std::fs::create_dir_all(dir).map_err(|e| e.to_string())?;
        }
        std::fs::write(&p, &text).map_err(|e| e.to_string())?;
        println!("wrote {}", p.display());
        let c = root.join(COMMANDS_FILE);
        std::fs::write(&c, crate::registry::markdown()).map_err(|e| e.to_string())?;
        println!("wrote {}", c.display());
    } else {
        print!("{text}");
    }
    if let (Some(head), Some(dirty)) = (git(&["log", "-1", "--format=%h %cs %s"]), git(&["status", "--porcelain"])) {
        println!("\nHEAD: {head}\nUncommitted files: {}", dirty.lines().count());
    }
    Ok(())
}

fn days_from_civil(y: i64, m: i64, d: i64) -> i64 {
    let y = if m <= 2 { y - 1 } else { y };
    let era = y.div_euclid(400);
    let yoe = y - era * 400;
    let doy = (153 * (if m > 2 { m - 3 } else { m + 9 }) + 2) / 5 + d - 1;
    era * 146097 + yoe * 365 + yoe / 4 - yoe / 100 + doy - 719468
}

fn parse_date(s: &str) -> Option<i64> {
    let mut it = s.trim().split('-');
    let (y, m, d) = (it.next()?.parse().ok()?, it.next()?.parse().ok()?, it.next()?.parse().ok()?);
    Some(days_from_civil(y, m, d))
}

/// `pt docs-check`: exit 1 when the documentation harness finds a problem.
pub fn check_cmd(_args: &[String]) -> Result<(), String> {
    let root = root();
    let mut problems: Vec<String> = vec![];
    let mut mds = vec![];
    walk(&root.join("docs"), "md", &mut mds);
    mds.push(root.join("CLAUDE.md"));
    let rel = |p: &Path| p.strip_prefix(&root).unwrap_or(p).to_string_lossy().replace('\\', "/");

    for p in &mds {
        let name = rel(p);
        let text = read(p);
        let budget = if name == "docs/STATUS.md" { STATUS_BUDGET } else { DOC_BUDGET };
        if !APPEND_ONLY.contains(&name.as_str()) && !name.starts_with("docs/generated/") && text.len() > budget {
            problems.push(format!("{name}: {} bytes, over its {} byte budget (split it by lifetime: see docs/README.md)", text.len(), budget));
        }
        let mut in_code = false;
        for (i, line) in text.lines().enumerate() {
            let n = i + 1;
            if line.trim_start().starts_with("```") {
                in_code = !in_code;
                continue;
            }
            if line.contains('\t') {
                problems.push(format!("{name}:{n}: tab character (a mangled backslash escape such as \\t in a Windows path)"));
            }
            if has_bare_drive(line) {
                problems.push(format!("{name}:{n}: drive path without a backslash after the colon (a mangled path)"));
            }
            if line.starts_with('#') && !in_code && !name.starts_with("docs/generated/") {
                let h = line.trim_start_matches('#').trim().to_lowercase();
                if let Some(b) = BANNED_HEADINGS.iter().find(|b| h.contains(*b)) {
                    problems.push(format!("{name}:{n}: heading '{}' is a banned kind of section (\"{b}\"); name the fix or the route instead (CLAUDE.md)", line.trim()));
                }
            }
            if !in_code {
                for target in link_targets(line) {
                    let t = target.split('#').next().unwrap_or("");
                    if t.is_empty() || t.starts_with("http") || t.starts_with("mailto:") {
                        continue;
                    }
                    let base = p.parent().unwrap_or(&root);
                    if !base.join(t).exists() {
                        problems.push(format!("{name}:{n}: broken link '{target}'"));
                    }
                }
            }
        }
    }

    // STATUS must carry an update date, and it must not trail the last commit by more than a day.
    let status = read(&root.join("docs/STATUS.md"));
    let updated = status.lines().take(12).find_map(|l| l.strip_prefix("Updated:")).and_then(|r| parse_date(r.split_whitespace().next().unwrap_or("")));
    match (updated, git(&["log", "-1", "--format=%cs"]).and_then(|d| parse_date(&d))) {
        (None, _) => problems.push("docs/STATUS.md: no 'Updated: YYYY-MM-DD' line in the first lines".into()),
        (Some(u), Some(head)) if u + 1 < head => problems.push(format!("docs/STATUS.md: updated {} days before the last commit; rewrite it at wrap-up", head - u)),
        _ => {}
    }

    // Every doc is reachable from the index.
    let index = read(&root.join("docs/README.md"));
    for p in &mds {
        let name = rel(p);
        if let Some(f) = name.strip_prefix("docs/") {
            if f != "README.md" && !f.starts_with("generated/") && !index.contains(&format!("({f})")) {
                problems.push(format!("{name}: not linked from docs/README.md"));
            }
        }
    }

    // The generated state is current.
    let want = state_text(&root);
    if read(&root.join(STATE_FILE)) != want {
        problems.push(format!("{STATE_FILE}: stale; run `pt status --write`"));
    }
    if read(&root.join(COMMANDS_FILE)) != crate::registry::markdown() {
        problems.push(format!("{COMMANDS_FILE}: stale (a command was added or changed); run `pt status --write`"));
    }

    if problems.is_empty() {
        println!("docs-check: {} documents, 0 problems", mds.len());
        Ok(())
    } else {
        for p in &problems {
            println!("PROBLEM {p}");
        }
        Err(format!("docs-check: {} problem(s)", problems.len()))
    }
}

/// True when the line has `D:` followed by a letter (not a backslash or slash): `D:Fekri...`.
fn has_bare_drive(line: &str) -> bool {
    let b = line.as_bytes();
    b.windows(3).enumerate().any(|(i, w)| w[0] == b'D' && w[1] == b':' && w[2].is_ascii_alphabetic() && (i == 0 || !b[i - 1].is_ascii_alphanumeric()))
}

/// The targets of `[text](target)` links on one line.
fn link_targets(line: &str) -> Vec<String> {
    let mut v = vec![];
    let mut rest = line;
    while let Some(i) = rest.find("](") {
        let after = &rest[i + 2..];
        if let Some(j) = after.find(')') {
            v.push(after[..j].trim().to_string());
            rest = &after[j..];
        } else {
            break;
        }
    }
    v
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn csv_handles_quotes_and_newlines() {
        let r = parse_csv("a,b\n1,\"x, \"\"y\"\"\nz\"\n");
        assert_eq!(r.len(), 2);
        assert_eq!(r[1][1], "x, \"y\"\nz");
    }

    #[test]
    fn dates_order() {
        assert_eq!(parse_date("2026-10-11").unwrap() - parse_date("2026-10-10").unwrap(), 1);
        assert_eq!(parse_date("2026-03-01").unwrap() - parse_date("2026-02-28").unwrap(), 1);
    }

    #[test]
    fn mangled_drive_paths_are_found() {
        assert!(has_bare_drive("tiles under D:Fekricorpusdem"));
        assert!(!has_bare_drive("tiles under D:\\Fekri\\corpus"));
        assert!(!has_bare_drive("AD:x"));
    }

    #[test]
    fn links_are_extracted() {
        assert_eq!(link_targets("see [a](x.md) and [b](y.md#z)"), vec!["x.md", "y.md#z"]);
    }
}
